const es: Dict = { 'Inicio (fila)': 'Inicio', 'Final (fila)': 'Final', LMXJVSD: 'LMXJVSD' }

const DICTS: Record<Lang, Dict> = { es, en, fr }

function detect(): Lang {
  try {
    const saved = localStorage.getItem('trazo.lang') as Lang | null
    if (saved && saved in DICTS) return saved
  } catch {}
  return 'fr'
}

let current: Lang = detect()
document.documentElement.lang = current

export function getLang() {
  return current
}

export function setLangGlobal(l: Lang) {
  current = l
  document.documentElement.lang = l
  try {
    localStorage.setItem('trazo.lang', l)
  } catch {}
}

export function t(key: string, vars?: Record<string, string | number>) {
  let s = DICTS[current][key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

// plural helper: tn(n, '{n} pantalla', '{n} pantallas')
export function tn(n: number, one: string, many: string) {
  return t(n === 1 ? one : many, { n })
}

export const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: current, setLang: () => {} })

// subscribing to the context re-renders the caller (memo components included) when the language changes
export function useLang() {
  return useContext(LangContext)
}
